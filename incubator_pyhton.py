"""
FUZZY LOGIC SUGENO (MIMO) - SIMULATOR INKUBATOR PENETAS TELUR
Input  : 1. Suhu (°C), 2. Kelembaban (%RH)
Output : 1. Daya Blower (%), 2. Daya Kipas (%)
Metode : AND = min, Defuzzifikasi = Weighted Average (Rata-rata Tertimbang)
"""
import numpy as np
import matplotlib.pyplot as plt

# ======================================================================
# 1. INPUT SIMULATOR (Ubah nilai di sini untuk pengujian)
# ======================================================================
INPUT_SUHU = 36.8       # Contoh Suhu ruang inkubator
INPUT_KELEMBABAN = 42.0 # Contoh Kelembaban (Kondisi Kering)

# ======================================================================
# 2. PARAMETER FUNGSI KEANGGOTAAN INPUT (Suhu & Kelembaban)
#    Format Segitiga  : [a, b, c]
#    Format Trapesium : [a, b, c, d] (Untuk bahu kiri / bahu kanan)
# ======================================================================
MF = {
    "suhu": {
        "Dingin": (0, 0, 36.0, 37.2),      # Bahu Kiri
        "Normal": (36.5, 37.5, 38.5),      # Segitiga
        "Panas":  (37.8, 39.0, 50.0, 50.0) # Bahu Kanan
    },
    "kelembaban": {
        "Kering": (0, 0, 45.0, 55.0),      # Bahu Kiri
        "Ideal":  (50.0, 55.0, 65.0),      # Segitiga
        "Lembab": (60.0, 70.0, 100.0, 100.0) # Bahu Kanan
    }
}

# ======================================================================
# 3. RULE BASE (9 ATURAN SUGENO) & TARGET OUTPUT (SINGLETON)
#    Format: (Suhu, Kelembaban) -> [Bobot_Blower, Bobot_Kipas]
# ======================================================================
RULES = {
    ("Dingin", "Kering"): [100.0, 0.0],
    ("Dingin", "Ideal"):  [100.0, 0.0],
    ("Dingin", "Lembab"): [100.0, 10.0],

    ("Normal", "Kering"): [0.0, 0.0],
    ("Normal", "Ideal"):  [0.0, 10.0],
    ("Normal", "Lembab"): [0.0, 40.0],

    ("Panas", "Kering"):  [0.0, 40.0],   # Cerdas: Kipas ditahan 40% agar tidak makin kering
    ("Panas", "Ideal"):   [0.0, 70.0],
    ("Panas", "Lembab"):  [0.0, 100.0]
}

# Histeresis / Deadband
DEAD_BAND = 15.0

# ======================================================================
# 4. FUNGSI MATEMATIKA (FUZZIFIKASI & DEFUZZIFIKASI)
# ======================================================================
def segitiga(x, a, b, c):
    x = np.atleast_1d(np.asarray(x, dtype=float))
    y = np.zeros_like(x)
    naik = (x > a) & (x <= b)
    turun = (x > b) & (x < c)
    y[naik] = (x[naik] - a) / (b - a)
    y[turun] = (c - x[turun]) / (c - b)
    return y

def trapesium(x, a, b, c, d):
    x = np.atleast_1d(np.asarray(x, dtype=float))
    y = np.zeros_like(x)
    y[(x >= b) & (x <= c)] = 1.0
    if b > a:
        naik = (x > a) & (x < b)
        y[naik] = (x[naik] - a) / (b - a)
    if d > c:
        turun = (x > c) & (x < d)
        y[turun] = (d - x[turun]) / (d - c)
    return y

def keanggotaan(x, p):
    return segitiga(x, *p) if len(p) == 3 else trapesium(x, *p)

def inferensi(s, k):
    # Fuzzifikasi Suhu & Kelembaban
    mu_suhu = {nama: float(keanggotaan(s, p)[0]) for nama, p in MF["suhu"].items()}
    mu_kel  = {nama: float(keanggotaan(k, p)[0]) for nama, p in MF["kelembaban"].items()}

    pembilang_blower = 0.0
    pembilang_kipas = 0.0
    penyebut = 0.0
    aktif = []

    print("[1] HASIL FUZZIFIKASI INPUT")
    print(f"    Suhu {s}°C        : { {n: round(v,3) for n,v in mu_suhu.items()} }")
    print(f"    Kelembaban {k}%   : { {n: round(v,3) for n,v in mu_kel.items()} }\n")

    print("[2] EVALUASI ATURAN (MIN) & SINGLETON SUGENO")
    for (suhu_label, kel_label), (bobot_blower, bobot_kipas) in RULES.items():
        w = min(mu_suhu[suhu_label], mu_kel[kel_label])
        if w > 0:
            pembilang_blower += (w * bobot_blower)
            pembilang_kipas  += (w * bobot_kipas)
            penyebut += w
            aktif.append((suhu_label, kel_label, w, bobot_blower, bobot_kipas))
            print(f"    IF {suhu_label:<6} AND {kel_label:<6} THEN Blower={bobot_blower:<3} Kipas={bobot_kipas:<3} | Bobot(w) = {w:.3f}")

    # Zero Division Guard
    if penyebut == 0:
        return 0.0, 0.0, mu_suhu, mu_kel, aktif

    y_blower = pembilang_blower / penyebut
    y_kipas  = pembilang_kipas / penyebut

    return y_blower, y_kipas, mu_suhu, mu_kel, aktif

# ======================================================================
# 5. PEMBUATAN GRAFIK VISUAL (KHUSUS UNTUK LAPORAN / GOOGLE COLAB)
# ======================================================================
def gambar_himpunan(ax, variabel, batas_x, nilai_input, satuan):
    WARNA = ["#1F77B4", "#2CA02C", "#D62728"] # Biru, Hijau, Merah
    x = np.linspace(batas_x[0], batas_x[1], 1000)

    for (nama, p), c in zip(MF[variabel].items(), WARNA):
        y = keanggotaan(x, p)
        ax.plot(x, y, color=c, lw=2.5, label=nama)

    ax.axvline(nilai_input, color="k", ls="--", lw=1.5)
    ax.text(nilai_input, 1.05, f" Input = {nilai_input} ", ha="center", fontsize=9,
            bbox=dict(boxstyle="round", fc="white", ec="black"))

    ax.set_title(f"Himpunan Fuzzy {variabel.capitalize()} ({satuan})", fontsize=11, fontweight="bold")
    ax.set_xlim(batas_x); ax.set_ylim(-0.05, 1.2)
    ax.set_ylabel("Derajat Keanggotaan (\u03bc)")
    ax.grid(True, linestyle=":", alpha=0.6)
    ax.legend(loc="upper right", fontsize=8)

def gambar_output_sugeno(ax, nama_output, z_final, target_bobot, warna_tiang):
    # Menggambar tiang (singleton) standar untuk Blower / Kipas
    for bobot in target_bobot:
        ax.vlines(bobot, 0, 1.0, color="gray", alpha=0.3, lw=2, linestyles="dashed")

    # Menandai Output Final dengan garis tebal
    ax.axvline(z_final, color=warna_tiang, lw=3)
    ax.text(z_final, 0.5, f" Z* = {z_final:.1f}% ", ha="center", fontsize=10, fontweight="bold",
            bbox=dict(boxstyle="round", fc="white", ec=warna_tiang))

    ax.set_title(f"Output Defuzzifikasi {nama_output}", fontsize=11, fontweight="bold")
    ax.set_xlim(-5, 105); ax.set_ylim(0, 1.1)
    ax.set_xticks([0, 10, 40, 70, 100])
    ax.set_xlabel("Persentase Daya (%)")
    ax.grid(True, linestyle=":", alpha=0.6)

def jalankan_simulator():
    print("=================================================================")
    print("      SIMULATOR INKUBATOR PENETAS TELUR (SUGENO MIMO)            ")
    print(f"      Suhu: {INPUT_SUHU}°C  |  Kelembaban: {INPUT_KELEMBABAN}% ")
    print("=================================================================\n")

    # Jalankan perhitungan
    y_blower, y_kipas, mu_suhu, mu_kel, aktif = inferensi(INPUT_SUHU, INPUT_KELEMBABAN)

    # Filter Deadband (Histeresis)
    blower_final = y_blower if y_blower > DEAD_BAND else 0.0
    kipas_final  = y_kipas if y_kipas > DEAD_BAND else 0.0

    print("\n[3] HASIL AKHIR (DEFUZZIFIKASI & HISTERESIS)")
    print(f"    Persentase Daya Blower Mentah : {y_blower:.2f}%")
    print(f"    Persentase Daya Kipas Mentah  : {y_kipas:.2f}%")
    print("-" * 65)
    print(f"    => STATUS BLOWER (Pemanas)    : {blower_final:.1f}% (ON)" if blower_final > 0 else "    => STATUS BLOWER (Pemanas)    : MATI (< 15%)")
    print(f"    => STATUS KIPAS (Pendingin)   : {kipas_final:.1f}% (ON)" if kipas_final > 0 else "    => STATUS KIPAS (Pendingin)   : MATI (< 15%)")
    print("=================================================================\n")

    # --- MEMBANGUN TAMPILAN GRAFIK 2x2 ---
    fig, ax = plt.subplots(2, 2, figsize=(12, 8))

    # Grafik Input Kiri Atas & Kanan Atas
    gambar_himpunan(ax[0, 0], "suhu", (35.0, 40.0), INPUT_SUHU, "°C")
    gambar_himpunan(ax[0, 1], "kelembaban", (30.0, 80.0), INPUT_KELEMBABAN, "%")

    # Grafik Output Kiri Bawah & Kanan Bawah
    gambar_output_sugeno(ax[1, 0], "BLOWER (Pemanas)", blower_final, [0, 100], "#D62728")
    gambar_output_sugeno(ax[1, 1], "KIPAS (Pendingin)", kipas_final, [0, 10, 40, 70, 100], "#1F77B4")

    fig.suptitle(f"Fuzzy Sugeno Inkubator | Suhu: {INPUT_SUHU}°C, Kelembaban: {INPUT_KELEMBABAN}%",
                 fontsize=14, fontweight="bold")
    plt.tight_layout()
    plt.show()

# Eksekusi Program
if __name__ == "__main__":
    jalankan_simulator()